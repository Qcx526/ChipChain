def test_missing_and_invalid_elf_inputs_use_stable_errors(tmp_path: Path) -> None:
    """Filesystem and CLE failures should not leak backend exception classes."""

    missing = ProgramArtifact(
        id="missing-arm-elf",
        architecture="arm",
        artifact_type="elf",
        path=str(tmp_path / "missing.elf"),
    )
    with pytest.raises(InvalidAnalysisInputError, match="not a file"):
        AngrAnalyzer().analyze(missing)

    invalid_path = tmp_path / "invalid.elf"
    invalid_path.write_bytes(b"not an ELF")
    invalid = ProgramArtifact(
        id="invalid-arm-elf",
        architecture="arm",
        artifact_type="elf",
        path=str(invalid_path),
    )
    with pytest.raises(InvalidAnalysisInputError, match="could not load"):
        AngrAnalyzer().analyze(invalid)


def test_end_to_end_demo_reports_recovered_program_facts() -> None:
    """The runnable demo must report facts and a real recovered call path."""

    repository_root = Path(__file__).resolve().parents[1]
    completed = subprocess.run(
        [sys.executable, "examples/arm_angr_analysis_demo.py"],
        cwd=repository_root,
        check=False,
        capture_output=True,
        text=True,
    )

    assert completed.returncode == 0, completed.stderr
    assert "Artifact: synthetic-arm-call-chain" in completed.stdout
    assert "Architecture: arm" in completed.stdout
    assert "Functions recovered: 5" in completed.stdout
    assert "Calls recovered: 3" in completed.stdout
    assert "Unresolved calls: 1" in completed.stdout
    assert "Evidence count: 3" in completed.stdout
    assert "GraphPath:" in completed.stdout
    for forbidden_claim in (
        "Vulnerability Found",
        "Exploit Confirmed",
        "Hardware Weakness",
        "Privilege Escalation",
    ):
        assert forbidden_claim not in completed.stdout
